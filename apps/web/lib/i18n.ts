// Arayüz dili (tr/en). Seçim `lang` çerezinde tutulur; ölçüm ve API dilden bağımsızdır.
export type Lang = "tr" | "en";
export const LANG_COOKIE = "lang";

export function parseLang(v: string | null | undefined): Lang | null {
  return v === "en" || v === "tr" ? v : null;
}

/** Çerez yoksa tarayıcı diline bak: Türkçe değilse İngilizce. */
export function langFromAccept(accept: string | null | undefined): Lang {
  return /(^|,)\s*tr\b/i.test(accept ?? "") ? "tr" : "en";
}

